#!/usr/bin/env node
/**
 * build-process-registry.cjs — own scheduled processes by authorization scope,
 * and make both halves independently saveable and recallable.
 *
 * THE PROBLEM
 *   Every scheduled process lived in one gitignored file, mixing two entirely
 *   different kinds of ownership:
 *
 *     system_framework (20)  platform-owned, SUPER_ADMIN authority, part of TNF
 *     tenant           (14)  user-owned, the operator's own automation
 *
 *   One file meant one persistence policy, one authorization boundary, and one
 *   blast radius. Because it was gitignored it was recoverable from nowhere:
 *   when it vanished, every cron job threw "not registered" and exited 0 for
 *   ~11 weeks. Publishing it would have shipped the operator's private
 *   automation to a public repo; not publishing it left TNF's own schedule
 *   unrecoverable. There was no single correct answer because two different
 *   things were in one place.
 *
 * THE SPLIT
 *
 *   data/protocols/system-processes.json    system_framework, TRACKED in git
 *                                           platform schedule; ships with TNF;
 *                                           recoverable by any clone; edits are
 *                                           SUPER_ADMIN + approval-gated.
 *
 *   ~/.config/tnf/processes.json            tenant, user-owned, NEVER in repo
 *                                           the operator's own automation; the
 *                                           user backs it up like any config;
 *                                           no approval needed to edit.
 *
 *   data/protocols/cron-jobs.registry.json  GENERATED merge of both.
 *   data/protocols/chronological-process-catalog.json
 *
 *   The generated files stay exactly where all eight existing consumers already
 *   read them, so nothing downstream changes. Losing them is no longer
 *   catastrophic: `--build` reconstructs them from the two owned stores.
 *
 * RUNTIME STATE IS NOT POLICY
 *   cron-jobs.control-plane-state.json (run history, timings, errors) stays
 *   gitignored and unowned by either store. It is an observation, not a
 *   declaration — regenerated by running, never restored.
 *
 * USAGE
 *   node scripts/protocols/build-process-registry.cjs --split   # one-time migration
 *   node scripts/protocols/build-process-registry.cjs           # rebuild generated files
 *   node scripts/protocols/build-process-registry.cjs --verify  # generated == sources?
 *
 * EXIT  0 ok · 1 drift/failure · 2 cannot run (missing sources)
 */
'use strict';

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const REPO = path.resolve(__dirname, '..', '..');
const SYSTEM_STORE = path.join(REPO, 'data', 'protocols', 'system-processes.json');
const USER_STORE =
  process.env.TNF_USER_PROCESS_STORE || path.join(os.homedir(), '.config', 'tnf', 'processes.json');
const OUT_REGISTRY = path.join(REPO, 'data', 'protocols', 'cron-jobs.registry.json');
const OUT_CATALOG = path.join(REPO, 'data', 'protocols', 'chronological-process-catalog.json');

const MODE = process.argv.includes('--split')
  ? 'split'
  : process.argv.includes('--verify')
    ? 'verify'
    : 'build';

const readJson = (p, fb = null) => {
  try {
    return JSON.parse(fs.readFileSync(p, 'utf8'));
  } catch {
    return fb;
  }
};
const writeJson = (p, v) => {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, `${JSON.stringify(v, null, 2)}\n`, 'utf8');
};

/** Deterministic ordering so a rebuild never produces a spurious diff. */
const byId = (a, b) => a.schedule_id.localeCompare(b.schedule_id);
const sortKeys = (o) =>
  Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));

function splitStores() {
  const registry = readJson(OUT_REGISTRY);
  const catalog = readJson(OUT_CATALOG);
  if (!registry || !catalog) {
    console.error('[build-process-registry] BLOCKED: canonical registry/catalog missing; nothing to split');
    process.exit(2);
  }

  const jobs = registry.jobs || [];
  const entries = catalog.entries || {};
  const store = (scope) => {
    const ids = jobs.filter((j) => j.scope === scope).map((j) => j.schedule_id);
    return {
      spec: `tnf/${scope === 'system_framework' ? 'system' : 'user'}-processes/0.1`,
      scope,
      authority:
        scope === 'system_framework'
          ? 'SUPER_ADMIN — platform schedule, approval-gated, versioned in git'
          : 'tenant owner — the operator\'s own automation, never published',
      jobs: jobs.filter((j) => j.scope === scope).sort(byId),
      catalog: sortKeys(Object.fromEntries(ids.filter((i) => entries[i]).map((i) => [i, entries[i]]))),
    };
  };

  writeJson(SYSTEM_STORE, store('system_framework'));
  writeJson(USER_STORE, store('tenant'));

  const sys = readJson(SYSTEM_STORE);
  const usr = readJson(USER_STORE);
  console.log('[build-process-registry] split complete');
  console.log(`  system (tracked): ${sys.jobs.length} job(s) -> ${path.relative(REPO, SYSTEM_STORE)}`);
  console.log(`  user   (private): ${usr.jobs.length} job(s) -> ${USER_STORE.replace(os.homedir(), '~')}`);

  const orphans = jobs.filter((j) => j.scope !== 'system_framework' && j.scope !== 'tenant');
  if (orphans.length) {
    console.error(`  FAIL: ${orphans.length} job(s) have neither scope and would be dropped:`);
    for (const o of orphans) console.error(`    ${o.schedule_id} scope=${o.scope}`);
    process.exit(1);
  }
}

function merge() {
  const sys = readJson(SYSTEM_STORE);
  const usr = readJson(USER_STORE, { jobs: [], catalog: {} });

  if (!sys) {
    console.error(`[build-process-registry] BLOCKED: ${path.relative(REPO, SYSTEM_STORE)} missing`);
    console.error('  The system schedule ships with TNF and is recoverable from git — restore it.');
    process.exit(2);
  }

  // A user store is legitimately absent on a fresh install; the platform
  // schedule alone is a valid, complete configuration.
  const jobs = [...(sys.jobs || []), ...(usr.jobs || [])].sort(byId);
  const dupes = jobs.map((j) => j.schedule_id).filter((id, i, a) => a.indexOf(id) !== i);
  if (dupes.length) {
    console.error(`[build-process-registry] FAIL: id declared in both stores: ${[...new Set(dupes)].join(', ')}`);
    console.error('  Ownership must be unambiguous — a process belongs to exactly one authority.');
    process.exit(1);
  }

  return {
    registry: {
      spec: 'tnf/cron-jobs-registry/0.1',
      generated_at: new Date().toISOString(),
      generator: 'scripts/protocols/build-process-registry.cjs',
      sources: {
        system_framework: path.relative(REPO, SYSTEM_STORE),
        tenant: USER_STORE.replace(os.homedir(), '~'),
      },
      jobs,
    },
    catalog: {
      spec: 'tnf/chronological-process-catalog/0.1',
      generated_at: new Date().toISOString(),
      generator: 'scripts/protocols/build-process-registry.cjs',
      entries: sortKeys({ ...(sys.catalog || {}), ...(usr.catalog || {}) }),
    },
  };
}

/** Compare ignoring generated_at, which changes on every run by design. */
const stable = (o) => {
  const c = JSON.parse(JSON.stringify(o));
  delete c.generated_at;
  return JSON.stringify(c);
};

function main() {
  if (MODE === 'split') return splitStores();

  const built = merge();

  if (MODE === 'verify') {
    const curReg = readJson(OUT_REGISTRY);
    const curCat = readJson(OUT_CATALOG);
    const drift = [];
    if (!curReg || stable(curReg) !== stable(built.registry)) drift.push('cron-jobs.registry.json');
    if (!curCat || stable(curCat) !== stable(built.catalog)) drift.push('chronological-process-catalog.json');
    if (drift.length) {
      console.error(`[build-process-registry] DRIFT: ${drift.join(', ')} does not match its sources`);
      console.error('  Someone edited a generated file directly. Edit the owning store instead, then rebuild.');
      process.exit(1);
    }
    const n = built.registry.jobs.length;
    console.log(`[build-process-registry] OK: generated files match their sources (${n} job(s))`);
    return;
  }

  writeJson(OUT_REGISTRY, built.registry);
  writeJson(OUT_CATALOG, built.catalog);
  const sys = built.registry.jobs.filter((j) => j.scope === 'system_framework').length;
  console.log(
    `[build-process-registry] rebuilt: ${built.registry.jobs.length} job(s) ` +
      `(${sys} system, ${built.registry.jobs.length - sys} tenant)`
  );
}

main();
